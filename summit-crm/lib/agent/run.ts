const Inputs = {
  list_files: z.object({}).strict(),
  read_file: z.object({ path: z.string().min(1), start_line: z.number().int().min(1).optional(), end_line: z.number().int().min(1).optional() }).strict(),
  search: z.object({ query: z.string().min(1), path: z.string().optional() }).strict(),
  edit_file: z.object({ path: z.string().min(1), old_text: z.string().min(1), new_text: z.string() }).strict(),
  create_file: z.object({ path: z.string().min(1), content: z.string() }).strict(),
  view_live_page: z.object({ path: z.string().min(1) }).strict(),
  list_images: z.object({}).strict(),
} as const;
type ToolName = keyof typeof Inputs;

export const label = (name: string, input: Record<string, unknown>) => {
  const file = typeof input.path === "string" ? String(input.path).split("/").pop() : "";
  switch (name) {
    case "read_file": return `Reading ${file}`;
    case "search": return `Searching for “${String(input.query ?? "").slice(0, 40)}”`;
    case "edit_file": return `Editing ${file}`;
    case "create_file": return `Creating ${file}`;
    case "view_live_page": return `Looking at ${input.path} on the live site`;
    case "list_images": return "Checking the images";
    default: return "Looking at the site’s files";
  }
};

/** The repository as this session sees it: the commit it started from, plus its staged edits. */
class Workspace {
  private cache = new Map<string, string | null>();
  constructor(private s: AgentSession) {}
  private staged = new Map<string, { original: string | null; content: string }>();
  async load() {
    for (const f of await stagedFiles(this.s.id)) this.staged.set(f.path, { original: f.original, content: f.content });
  }
  async original(path: string) {
    if (!this.cache.has(path)) this.cache.set(path, await readAt(path, this.s.baseSha));
    return this.cache.get(path)!;
  }
  async current(path: string) {
    return this.staged.get(path)?.content ?? (await this.original(path));
  }
  async write(path: string, content: string) {
    const original = this.staged.has(path) ? this.staged.get(path)!.original : await this.original(path);
    await stageFile(this.s.id, { path, original, content });
    if (original !== null && content === original) this.staged.delete(path);
    else this.staged.set(path, { original, content });
  }
  changed() {
    return [...this.staged.keys()];
  }
  async files() {
    const all = await tree(this.s.baseSha);
    return { all, editable: all.filter((e) => canEdit(e.path)) };
  }
}

const numbered = (text: string, from = 1, to?: number) => {
  const lines = text.split("\n");
  const end = Math.min(lines.length, to ?? lines.length);
  const out: string[] = [];
  for (let i = from; i <= end; i++) out.push(`${String(i).padStart(5)}  ${lines[i - 1]}`);
  return { text: out.join("\n"), total: lines.length };
};

function pageText(html: string) {
  return html
    .replace(/<(script|style|svg|noscript)[\s\S]*?<\/\1>/gi, " ")
    .replace(/<h([1-3])[^>]*>/gi, (_, n) => `\n${"#".repeat(Number(n))} `)
    .replace(/<\/(p|div|section|li|h\d|header|footer|nav|a)>/gi, "\n")
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&rsquo;|&#8217;/g, "’").replace(/&ldquo;|&rdquo;/g, "\"").replace(/&[a-z]+;/g, " ")
    .replace(/[ \t]+/g, " ")
    .replace(/\n\s*\n+/g, "\n")
    .trim();
}

async function runTool(ws: Workspace, name: ToolName, input: Record<string, unknown>): Promise<string> {
  switch (name) {
    case "list_files": {
      const { editable, all } = await ws.files();
      const pages = all.filter((e) => /^summit-suit\/[\w-]+\.html$/.test(e.path)).map((e) => e.path.replace("summit-suit/", ""));
      return [
        "Editable source files:",
        ...editable.map((e) => `- ${e.path} (${Math.round((e.size ?? 0) / 1000)} KB)`),
        "",
        `Generated pages (read-only, rebuilt on deploy): ${pages.join(", ")}`,
        ws.changed().length ? `\nYou have staged edits in: ${ws.changed().join(", ")}` : "",
      ].join("\n");
    }
    case "read_file": {
      const { path, start_line, end_line } = Inputs.read_file.parse(input);
      if (!canRead(path)) return `You can't read ${path}. Use list_files to see what's available.`;
      const text = await ws.current(path);
      if (text === null) return `${path} doesn't exist.`;
      const from = start_line ?? 1;
      const n = numbered(text, from, end_line ?? (start_line ? from + 400 : undefined));
      return `${path} (${n.total} lines)${!canEdit(path) ? " [read-only: generated]" : ""}\n${n.text}`;
    }
    case "search": {
      const { query, path } = Inputs.search.parse(input);
      const { editable } = await ws.files();
      const targets = path ? [path] : editable.map((e) => e.path);
      const q = query.toLowerCase();
      const hits: string[] = [];
      for (const p of targets) {
        if (!canRead(p)) continue;
        const text = await ws.current(p);
        if (!text) continue;
        text.split("\n").forEach((line, i) => {
          if (hits.length < 60 && line.toLowerCase().includes(q)) hits.push(`${p}:${i + 1}: ${line.trim().slice(0, 220)}`);
        });
      }
      return hits.length ? hits.join("\n") + (hits.length >= 60 ? "\n(first 60 matches)" : "") : `No matches for “${query}”.`;
    }
    case "edit_file": {
      const { path, old_text, new_text } = Inputs.edit_file.parse(input);
      if (!canEdit(path)) return `${path} can't be edited${canRead(path) ? " (it's generated: edit its source in summit-suit-src/ instead)" : ""}.`;
      const text = await ws.current(path);
      if (text === null) return `${path} doesn't exist.`;
      const count = text.split(old_text).length - 1;
      if (count === 0) return "old_text wasn't found. Read the file again and copy the passage exactly (including whitespace).";
      if (count > 1) return `old_text appears ${count} times. Include more surrounding text so it matches exactly once.`;
      await ws.write(path, text.replace(old_text, () => new_text));
      return `Edited ${path}.`;
    }
    case "create_file": {
      const { path, content } = Inputs.create_file.parse(input);
      if (!canEdit(path) || !path.startsWith("summit-suit-src/")) return `You can only create files in summit-suit-src/ (.py, .html, .json, .txt, .md).`;
      if ((await ws.current(path)) !== null) return `${path} already exists. Use edit_file.`;
      await ws.write(path, content);
      return `Created ${path}.`;
    }
    case "view_live_page": {
      const { path } = Inputs.view_live_page.parse(input);
      if (!/^\/[\w\-/]*$/.test(path)) return "Give a page path like / or /about.";
      const res = await fetch(new URL(path, config.site.url()), { cache: "no-store" }); // follows the www redirect
      if (!res.ok) return `The live site returned ${res.status} for ${path}.`;
      return pageText(await res.text()).slice(0, 15000);
    }
    case "list_images": {
      const { all } = await ws.files();
      const names = [...new Set(all.filter((e) => IMAGE_DIR.test(e.path)).map((e) => e.path.split("/").pop()!.replace(/-\d+\.\w+$/, "").replace(/\.\w+$/, "")))].sort();
      return names.join(", ");
    }
  }
}

/** If a run stopped between a tool call and its result, answer the call so the history stays valid. */
function sealDangling(messages: Anthropic.Beta.BetaMessageParam[]) {
  const last = messages[messages.length - 1];
  if (last?.role !== "assistant" || typeof last.content === "string") return messages;
  const open = last.content.filter((b): b is Anthropic.Beta.BetaToolUseBlock => b.type === "tool_use");
  if (!open.length) return messages;
  return [...messages, { role: "user" as const, content: open.map((u) => ({ type: "tool_result" as const, tool_use_id: u.id, is_error: true, content: "Interrupted before this ran." })) }];
}

/** Roughly what a turn cost, in cents (Claude Opus 5.5 list prices). */
function cents(u: Anthropic.Beta.BetaUsage) {
  const perM = (n: number | null | undefined, usd: number) => ((n ?? 0) / 1_000_000) * usd * 100;
  return perM(u.input_tokens, 4) + perM(u.output_tokens, 20) + perM(u.cache_read_input_tokens, 0.2) + perM(u.cache_creation_input_tokens, 5);
}

/**
 * Adds Kobe's message to the session and runs the agent until it answers (or the time budget
 * runs out, in which case it pauses and "continue" picks it up). Streams progress via `emit`.
 */
export async function runAgent(sessionId: string, userText: string, emit: (e: AgentEvent) => void) {
  const apiKey = await getSecret("anthropic");
  if (!apiKey) throw new Error("Add the Claude API key in Settings to use the website agent.");
  const session = await getSession(sessionId);
  if (!session) throw new Error("That conversation no longer exists.");
  if (session.status === "published" || session.status === "discarded") throw new Error("This change is closed. Start a new request.");

  const client = new Anthropic({ apiKey });
  const ws = new Workspace(session);
  await ws.load();
  const messages: Anthropic.Beta.BetaMessageParam[] = [...session.messages];
  messages.push({ role: "user", content: userText });
  await saveSession(sessionId, { status: "working", messages, error: null });

  const started = Date.now();
  let jsonRetries = 0;
  try {
    for (let turn = 0; turn < MAX_TURNS; turn++) {
      const stream = client.beta.messages.stream({
        model: MODEL,
        max_tokens: 64000,
        system: SYSTEM,
        tools,
        messages,
        output_config: { effort: "medium" },
        cache_control: { type: "ephemeral" },
        betas: ["server-side-fallback-2026-07-01"],
        fallbacks: "default",
      });
      stream.on("text", (delta) => emit({ type: "text", delta }));

      let message: Anthropic.Beta.BetaMessage;
      try {
        message = await stream.finalMessage();
        jsonRetries = 0;
      } catch (err) {
        // Only a tool input that couldn't be parsed at all is retried; API errors are real.
        if (err instanceof Anthropic.APIError || jsonRetries++ >= 2) throw err;
        continue;
      }
      await saveSession(sessionId, { addCents: cents(message.usage) });

      if (message.stop_reason === "refusal") {
        messages.push({ role: "assistant", content: message.content });
        emit({ type: "text", delta: "\n\nI can’t help with that change." });
        break;
      }
      messages.push({ role: "assistant", content: message.content });
      if (message.stop_reason === "pause_turn") continue;

      const uses = message.content.filter((b): b is Anthropic.Beta.BetaToolUseBlock => b.type === "tool_use");
      if (!uses.length) break; // answered Kobe

      const results: Anthropic.Beta.BetaToolResultBlockParam[] = [];
      for (const use of uses) {
        const name = use.name as ToolName;
        const input = (use.input ?? {}) as Record<string, unknown>;
        const schema = Inputs[name];
        const parsed = schema?.safeParse(input);
        if (message.stop_reason === "max_tokens" || !parsed?.success) {
          results.push({ type: "tool_result", tool_use_id: use.id, is_error: true, content: JSON.stringify({ INVALID_JSON: JSON.stringify(input).slice(0, 2000) }) });
          continue;
        }
        emit({ type: "tool", label: label(name, input) });
        try {
          results.push({ type: "tool_result", tool_use_id: use.id, content: await runTool(ws, name, input) });
        } catch (e) {
          results.push({ type: "tool_result", tool_use_id: use.id, is_error: true, content: e instanceof Error ? e.message : String(e) });
        }
        if (name === "edit_file" || name === "create_file") emit({ type: "files", paths: ws.changed() });
      }
      messages.push({ role: "user", content: results });
      await saveSession(sessionId, { messages });

      if (Date.now() - started > TIME_BUDGET_MS) {
        emit({ type: "paused", reason: "This one is taking a while. Send “continue” and I’ll pick up where I left off." });
        break;
      }
    }
    await saveSession(sessionId, { status: "idle", messages });
    emit({ type: "done" });
  } catch (e) {
    const msg =
      e instanceof Anthropic.AuthenticationError ? "The Claude API key was rejected. Check it in Settings."
      : e instanceof Anthropic.RateLimitError ? "Claude is busy right now. Try again in a minute."
      : e instanceof Anthropic.APIError ? `Claude API error ${e.status}: ${e.message}`
      : e instanceof Error ? e.message : String(e);
    await saveSession(sessionId, { status: "idle", messages: sealDangling(messages), error: msg });
    emit({ type: "error", message: msg });
  }
}
