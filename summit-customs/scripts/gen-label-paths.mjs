/**
 * Converts "SUMMIT CUSTOMS" set in Cormorant Garamond into SVG path data at
 * build time (opentype.js), so the intro can embroider real letterforms with
 * no font loading at runtime. Output is committed: three/label/labelPaths.ts
 * Re-run after changing the text: node scripts/gen-label-paths.mjs
 */
import { writeFileSync } from "node:fs";
import opentype from "opentype.js";

const TEXT = "SUMMIT CUSTOMS";
const CSS = "https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@500";
const css = await (await fetch(CSS, { headers: { "User-Agent": "Mozilla/5.0 (Windows NT 6.1)" } })).text();
const ttfUrl = css.match(/url\((https:[^)]+\.ttf)\)/)[1];
const font = opentype.parse(await (await fetch(ttfUrl)).arrayBuffer());

const size = 100;
const tracking = 0.16; // em
let x = 0;
const glyphs = [];
for (const ch of TEXT) {
  const g = font.charToGlyph(ch);
  const path = g.getPath(x, size, size);
  const d = path.toPathData(1);
  if (d) glyphs.push({ ch, d });
  x += (g.advanceWidth / font.unitsPerEm) * size + tracking * size;
}
const width = Math.ceil(x - tracking * size);
const out = `// Generated by scripts/gen-label-paths.mjs. Do not edit.
// "${TEXT}" in Cormorant Garamond 500, ${size}px, tracking ${tracking}em.
export const LABEL_VIEWBOX = "0 0 ${width} ${Math.ceil(size * 1.05)}";
export const labelGlyphs: { ch: string; d: string }[] = ${JSON.stringify(glyphs, null, 1)};
`;
writeFileSync("three/label/labelPaths.ts", out);
console.log(`label paths: ${glyphs.length} glyphs, width ${width}`);
