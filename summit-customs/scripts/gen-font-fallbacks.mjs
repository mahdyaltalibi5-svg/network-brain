/**
 * Generates metric-adjusted fallback @font-face rules so the web fonts swap in without layout shift
 * on every platform, not just where Times New Roman / Arial exist (next/font's built-in fallback).
 * For each fallback: size-adjust = avg char width(web font) / avg char width(fallback), weighted by
 * English letter frequency (the capsize / next/font approach); ascent/descent overrides follow.
 * Output: app/fonts/fallbacks.css. Run: node scripts/gen-font-fallbacks.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

// English letter frequencies (incl. space), as used by capsize for xWidthAvg
const FREQ = { " ": 0.1874, e: 0.0956, t: 0.0712, a: 0.0634, o: 0.0614, i: 0.0563, n: 0.0546, s: 0.0505, h: 0.0487, r: 0.0467, d: 0.0337, l: 0.0322, u: 0.0218, c: 0.0213, m: 0.0193, w: 0.0182, f: 0.017, y: 0.0164, g: 0.0153, p: 0.0149, b: 0.0113, v: 0.0076, k: 0.0063, x: 0.0011, j: 0.0009, q: 0.0007, z: 0.0006 };
const UA_TTF = "Mozilla/5.0 (Windows NT 6.1)";

async function gfont(family) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${family}`, { headers: { "User-Agent": UA_TTF } })).text();
  const url = css.match(/url\((https:[^)]+)\)/)[1];
  return opentype.parse(await (await fetch(url)).arrayBuffer());
}
const file = (p) => opentype.parse(new Uint8Array(readFileSync(p)).buffer);

function metrics(font) {
  const upm = font.unitsPerEm;
  let w = 0;
  for (const [ch, f] of Object.entries(FREQ)) w += (font.charToGlyph(ch).advanceWidth / upm) * f;
  const total = Object.values(FREQ).reduce((a, b) => a + b, 0);
  const os2 = font.tables.os2;
  const hhea = font.tables.hhea;
  const useTypo = os2 && (os2.fsSelection & 128) !== 0;
  return {
    avg: w / total,
    ascent: (useTypo ? os2.sTypoAscender : hhea.ascender) / upm,
    descent: Math.abs(useTypo ? os2.sTypoDescender : hhea.descender) / upm,
    lineGap: (useTypo ? os2.sTypoLineGap : hhea.lineGap) / upm,
  };
}

function face(family, primary, fallback, locals, style = "normal") {
  const size = primary.avg / fallback.avg;
  const pct = (v) => `${(v * 100).toFixed(2)}%`;
  return `@font-face {
  font-family: "${family}";
  font-style: ${style};
  src: ${locals.map((l) => `local("${l}")`).join(", ")};
  size-adjust: ${pct(size)};
  ascent-override: ${pct(primary.ascent / size)};
  descent-override: ${pct(primary.descent / size)};
  line-gap-override: ${pct(primary.lineGap / size)};
}`;
}

const cormorant = metrics(opentype.parse(new Uint8Array(readFileSync("app/fonts/og-cormorant-500.ttf")).buffer));
const cormorantItalic = metrics(opentype.parse(new Uint8Array(readFileSync("app/fonts/og-cormorant-500-italic.ttf")).buffer));
const manrope = metrics(await gfont("Manrope:wght@400"));
const timesLike = metrics(file("/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf")); // metric-compatible with Times New Roman / Tinos
const timesItalic = metrics(file("/usr/share/fonts/truetype/liberation/LiberationSerif-Italic.ttf"));
const notoSerifItalic = metrics(await gfont("Noto+Serif:ital,wght@1,400"));
const arialLike = metrics(file("/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf")); // metric-compatible with Arial / Arimo / Helvetica
const notoSerif = metrics(await gfont("Noto+Serif:wght@400"));
const roboto = metrics(await gfont("Roboto:wght@400"));

const TIMES = ["Times New Roman", "TimesNewRomanPSMT", "Times", "Liberation Serif", "LiberationSerif", "Tinos", "Tinos-Regular"];
const TIMES_I = ["Times New Roman Italic", "TimesNewRomanPS-ItalicMT", "Times Italic", "Liberation Serif Italic", "LiberationSerif-Italic", "Tinos Italic", "Tinos-Italic"];
const ARIAL = ["Arial", "ArialMT", "Helvetica", "Liberation Sans", "LiberationSans", "Arimo", "Arimo-Regular"];

const css = `/* Generated by scripts/gen-font-fallbacks.mjs. Do not edit. Metric-adjusted fallbacks: no layout shift when web fonts swap in. */
${face("Cormorant Fallback", cormorant, timesLike, TIMES)}
${face("Cormorant Fallback", cormorantItalic, timesItalic, TIMES_I, "italic")}
${face("Cormorant Fallback Android", cormorant, notoSerif, ["Noto Serif", "NotoSerif-Regular"])}
${face("Cormorant Fallback Android", cormorantItalic, notoSerifItalic, ["Noto Serif Italic", "NotoSerif-Italic"], "italic")}
${face("Manrope Fallback", manrope, arialLike, ARIAL)}
${face("Manrope Fallback Android", manrope, roboto, ["Roboto", "Roboto-Regular"])}
`;
writeFileSync("app/fonts/fallbacks.css", css);
console.log(css);
