/** Regenerates ../PLACEHOLDERS.md from every ph("…") and <Ph>…</Ph> in the source. */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dirs = ["content", "app", "components", "lib"];
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f)) files.push(p);
  }
};
dirs.forEach((d) => walk(join(root, d)));

const decode = (s) => s.replace(/&apos;|&rsquo;/g, "'").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();
const items = new Map(); // description -> Set(files)
for (const f of files) {
  if (f.endsWith("lib/ph.ts") || f.endsWith("components/ui/Rich.tsx")) continue;
  const src = readFileSync(f, "utf8");
  const found = [
    ...[...src.matchAll(/ph\("([^"]+)"\)/g)].map((m) => m[1]),
    ...[...src.matchAll(/<Ph>([\s\S]*?)<\/Ph>/g)].map((m) => m[1]),
    ...[...src.matchAll(/<PhotoSlot label="([^"]+)"/g)].map((m) => `photo: ${m[1]}`),
  ];
  for (const raw of found) {
    const d = decode(raw);
    if (d.includes("{")) continue; // dynamic children
    if (!items.has(d)) items.set(d, new Set());
    items.get(d).add(relative(root, f));
  }
}

const groups = [
  ["Business details (NAP, hours, links)", /address|ZIP|phone|email|latitude|longitude|Maps|hours|appointment|legal|year founded|Instagram|Google Business|LinkedIn|booking|directions|parking/i],
  ["Founder & E-E-A-T", /founder|training|experience|certification|clients, press/i],
  ["Pricing", /price|pricing|retainer|packages/i],
  ["Process, timelines & policies", /timeline|weeks|fittings|rush|aftercare|alteration|policy|lead time|canvas|hand finishing|measuring|travel|off-site|in-office|groomsmen|programme/i],
  ["Fabrics & mills", /mill|cloth/i],
  ["Reviews & photography", /testimonial|client name|photo|portrait/i],
];
const bucket = new Map(groups.map(([g]) => [g, []]));
bucket.set("Other", []);
for (const [d, where] of items) {
  const g = groups.find(([, re]) => re.test(d))?.[0] ?? "Other";
  bucket.get(g).push(`- [ ] ${d}  \n  <sub>${[...where].join(", ")}</sub>`);
}

let md = `# PLACEHOLDERS — facts Summit Customs must supply

Generated by \`npm run placeholders\` from the source. Don't edit by hand.
Each item renders on the site as a visible "[PLACEHOLDER: …]" marker. Placeholders are never published in JSON-LD; those fields are omitted until supplied.
Most business facts live in \`summit-customs/content/business.ts\`. Replace the \`ph("…")\` call with the real value.

**${items.size} items**
`;
for (const [g, list] of bucket) if (list.length) md += `\n## ${g} (${list.length})\n\n${list.sort().join("\n")}\n`;
md += `
## Also needed (not in copy)

- [ ] Real client reviews with permission → \`content/reviews.ts\` (enables Review + AggregateRating schema; set \`ratingSource\`)
- [ ] Logo SVG files → replace \`components/ui/Logo.tsx\` and \`public/logo.svg\`
- [ ] Opening hours as structured data → \`business.openingHours\` in \`content/business.ts\`
- [ ] Confirm studio commitments stated in copy: written quote confirmed before cutting · no obligation after the first consultation · 60–90 min first consultation · pattern kept on file · generous seam inlays for later alteration · posture notes and 20+ measurements
- [ ] Confirm the general trade figures used in copy are acceptable to publish (typical US price ranges, 6–12 week bespoke timeline)
`;
writeFileSync(join(root, "../PLACEHOLDERS.md"), md);
console.log(`PLACEHOLDERS.md: ${items.size} items`);
